"""
brain/response_engine.py — Structured Behavioral JSON Payload & Decoupled Response Router

Decouples raw LLM text output into structured behavioral components:
- Clean speech text (routed to Edge-TTS)
- Emotion state (routed to OLED / Desktop UI)
- Vocal audio SFX (routed to local audio clip player)
- Display animation / hardware action (routed to serial/WebSocket transport)
"""
from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, asdict
from typing import Optional, Dict, Any

logger = logging.getLogger(__name__)


@dataclass
class BehavioralPayload:
    """Structured response payload generated by MBUDDY."""
    speech: str
    emotion: str = "NORMAL"
    vocal_sfx: Optional[str] = None
    animation: Optional[str] = None
    tool_call: Optional[Dict[str, Any]] = None

    def to_json(self) -> str:
        return json.dumps(asdict(self), ensure_ascii=False)

    @classmethod
    def from_json(cls, json_str: str) -> Optional[BehavioralPayload]:
        try:
            data = json.loads(json_str)
            if isinstance(data, dict) and "speech" in data:
                return cls(
                    speech=data.get("speech", ""),
                    emotion=data.get("emotion", "NORMAL"),
                    vocal_sfx=data.get("vocal_sfx"),
                    animation=data.get("animation"),
                    tool_call=data.get("tool_call")
                )
        except Exception:
            pass
        return None


class ResponseEngine:
    """Parses, structures, and executes MBUDDY behavioral response payloads."""

    EMOTION_TAG_PATTERN = re.compile(
        r"\[(NORMAL|HAPPY|SAD|THINKING|SPEAKING|LISTENING|CONFUSED|EXCITED|WORRIED|ANGRY|LAUGHING|SURPRISED)\]",
        re.IGNORECASE
    )
    SFX_TAG_PATTERN = re.compile(r"\[SFX:\s*([a-zA-Z0-9_\-\.]+)\s*\]", re.IGNORECASE)
    ANIM_TAG_PATTERN = re.compile(r"\[(?:ANIM|ACTION):\s*([a-zA-Z0-9_\-\.]+)\s*\]", re.IGNORECASE)

    @classmethod
    def parse(cls, raw_text: str) -> BehavioralPayload:
        """
        Parse raw text or JSON string into a structured BehavioralPayload.
        Supports both structured JSON responses and legacy bracket protocol tags.
        """
        raw_clean = raw_text.strip()

        # 1. Attempt JSON parsing
        if raw_clean.startswith("{") and raw_clean.endswith("}"):
            payload = BehavioralPayload.from_json(raw_clean)
            if payload:
                return payload

        # 2. Bracket tag fallback parsing
        emotion = "NORMAL"
        vocal_sfx = None
        animation = None

        # Extract emotion tag
        emo_match = cls.EMOTION_TAG_PATTERN.search(raw_clean)
        if emo_match:
            emotion = emo_match.group(1).upper()
            raw_clean = cls.EMOTION_TAG_PATTERN.sub("", raw_clean)

        # Extract SFX tag
        sfx_match = cls.SFX_TAG_PATTERN.search(raw_clean)
        if sfx_match:
            vocal_sfx = sfx_match.group(1)
            raw_clean = cls.SFX_TAG_PATTERN.sub("", raw_clean)

        # Extract animation / action tag
        anim_match = cls.ANIM_TAG_PATTERN.search(raw_clean)
        if anim_match:
            animation = anim_match.group(1)
            raw_clean = cls.ANIM_TAG_PATTERN.sub("", raw_clean)

        # Clean remaining whitespace
        speech = " ".join(raw_clean.split()).strip()

        return BehavioralPayload(
            speech=speech,
            emotion=emotion,
            vocal_sfx=vocal_sfx,
            animation=animation
        )

    @classmethod
    def format_system_instruction(cls) -> str:
        """
        Response-format guidance for the system prompt.

        Deliberately empty. This used to offer the model a JSON envelope as an
        alternative to the tag format, but nothing ever called `parse()`, so a
        model that accepted the offer had its raw JSON spoken aloud. The tag
        format (`[FOCUSED] text`) is what the firmware parses and what the
        rest of the pipeline expects, and it is already specified in
        IDENTITY_CORE.

        `parse()` is still available for callers that want to accept a JSON
        envelope, and `unwrap_envelope()` below cleans one up defensively.

        Returns:
            str: an empty string.
        """
        return ""


def unwrap_envelope(text: str) -> str:
    """
    Return spoken text, unwrapping a JSON envelope if one was emitted.

    Nothing asks the model for JSON any more, but models occasionally produce
    it unprompted. Speaking `{"speech": "..."}` aloud is far worse than a
    slightly wrong emotion, so this pulls the speech field out and re-attaches
    the emotion as a tag.

    Args:
        text: raw model output

    Returns:
        The text to speak. Input that is not an envelope is returned unchanged.
    """
    import json as _json
    import re as _re

    raw = (text or "").strip()
    if not raw.startswith("{") or '"speech"' not in raw:
        return text

    # The model may wrap the object in a fenced code block.
    candidate = _re.sub(r"^```(?:json)?|```$", "", raw, flags=_re.MULTILINE).strip()
    try:
        data = _json.loads(candidate)
    except Exception:
        # Salvage the speech field even from malformed JSON rather than
        # letting braces reach the synthesizer.
        m = _re.search(r'"speech"\s*:\s*"((?:[^"\\]|\\.)*)"', candidate)
        if not m:
            return text
        speech = m.group(1).encode().decode("unicode_escape")
        return speech.strip()

    if not isinstance(data, dict):
        return text
    speech = str(data.get("speech") or "").strip()
    if not speech:
        return text

    emotion = str(data.get("emotion") or "").strip().upper()
    if emotion and not speech.lstrip().startswith("["):
        speech = f"[{emotion}] {speech}"
    return speech

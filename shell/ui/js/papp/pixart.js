/** SVG of a dot picture. [dim] draws the dark dots faintly, like an unlit dot-matrix screen. */
function draw(rows, { dim = true, cls = "" } = {}) {
  const h = rows.length, w = Math.max(...rows.map((r) => r.length));
  let d = "";
  rows.forEach((r, y) => { for (let x = 0; x < w; x++) {
    const on = r[x] === "#";
    if (on || dim) d += `<circle cx="${x * 10 + 5}" cy="${y * 10 + 5}" r="${on ? 3.9 : 1.5}" ${on ? "" : 'opacity=".16"'}/>`;
  } });
  return `<svg class="px ${cls}" viewBox="0 0 ${w * 10} ${h * 10}" fill="currentColor" aria-hidden="true">${d}</svg>`;
}

export const gameArt = (id, cls = "") => draw(G[id] || G.tap, { cls });
export const monsterArt = (name, cls = "") => draw(M[name] || M.Slime, { cls });
export const GAME_IDS = Object.keys(G);
export const MONSTER_NAMES = Object.keys(M);
